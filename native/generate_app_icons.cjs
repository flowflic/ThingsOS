// Build-time rasterization of the approved vector paths. Firmware uses only
// checked-in 4bpp constants; no SVG engine or sharp dependency on the device.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const sharp=require(process.env.THINGSOS_SHARP_MODULE||'sharp');
const base=path.join(__dirname,'firmware/main'),source=path.join(base,'assets/app-icons.json');
const design=JSON.parse(fs.readFileSync(source,'utf8'));
const preview=path.resolve(process.argv[2]||path.join(__dirname,'../build/app-icons-preview'));
fs.mkdirSync(preview,{recursive:true});
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
async function raster(svg,size,name){
  const high=await sharp(Buffer.from(svg),{density:288}).resize(size*4,size*4).flatten({background:'#fff'}).png().toBuffer();
  const {data,info}=await sharp(high).resize(size,size,{kernel:'lanczos3'}).greyscale().raw().toBuffer({resolveWithObject:true});
  if(info.channels!==1||data.length!==size*size)throw Error('Expected 8-bit gray raster');
  const packed=Buffer.alloc(Math.ceil(data.length/2));
  for(let i=0;i<data.length;i++){const gray=Math.round(data[i]/17);packed[i>>1]|=gray<<(i%2?0:4);data[i]=gray*17;}
  await sharp(data,{raw:{width:size,height:size,channels:1}}).png().toFile(path.join(preview,name+'.png'));
  return packed;
}
const format=b=>Array.from({length:Math.ceil(b.length/20)},(_,i)=>'    '+[...b.subarray(i*20,i*20+20)].map(v=>'0x'+v.toString(16).padStart(2,'0')).join(',')).join(',\n');
(async()=>{
  const arrays=[],manifest={source_sha256:hash(fs.readFileSync(source)),format:'4bpp gray, high nibble first',icons:[]};
  for(const icon of design.icons){
    const svg=`<svg xmlns="http://www.w3.org/2000/svg" width="58" height="58"><svg x=".5" y=".5" width="57" height="57" viewBox="0 0 24 24" color="${design.stroke}" fill="none" stroke="currentColor" stroke-width="${design.stroke_width}" stroke-linecap="round" stroke-linejoin="round">${icon.svg}</svg></svg>`;
    const bytes=await raster(svg,58,icon.name);arrays.push(bytes);manifest.icons.push({name:icon.name,bytes:bytes.length,sha256:hash(bytes)});
  }
  const border=await raster(`<svg xmlns="http://www.w3.org/2000/svg" width="108" height="108"><rect x="1" y="1" width="106" height="106" rx="19" fill="none" stroke="${design.border}" stroke-width="2"/></svg>`,108,'border');
  let code='// SPDX-License-Identifier: Apache-2.0\n// Generated by native/generate_app_icons.cjs from assets/app-icons.json.\n';
  code+='// Source SHA256: '+manifest.source_sha256+'\n';
  code+='#define APP_ICON_COUNT 6\n#define APP_ICON_GLYPH_SIZE 58\n#define APP_ICON_TILE_SIZE 108\n';
  code+='static const uint8_t app_icon_glyphs[APP_ICON_COUNT][1682]={\n'+arrays.map((b,i)=>'  { /* '+design.icons[i].name+' */\n'+format(b)+'\n  }').join(',\n')+'\n};\n';
  code+='static const uint8_t app_icon_border[5832]={\n'+format(border)+'\n};\n';
  fs.writeFileSync(path.join(base,'app_icons.inc'),code);
  manifest.border_sha256=hash(border);manifest.generated_sha256=hash(Buffer.from(code));
  fs.writeFileSync(path.join(preview,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
  console.log('Generated '+arrays.length+' approved icons + rounded tile, '+(arrays.reduce((n,b)=>n+b.length,0)+border.length)+' flash bytes.');
})().catch(e=>{console.error(e.message);process.exitCode=1;});
